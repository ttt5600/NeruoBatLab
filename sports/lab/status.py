"""Write lab/STATE.md: where the lab stands, rebuilt from the ledgers and the registry.

    python lab/status.py            # writes lab/STATE.md and prints it

Every agent reads STATE.md first instead of reconstructing the state from logs, the way a
long-running coding agent reads its progress file. It is generated, never edited: the ledger,
the lockbox log, the registry and topics.json stay the only sources of truth, so the file cannot
drift from them. loop.sh rebuilds it before every iteration.
"""
from __future__ import annotations

import json
import re
from collections import defaultdict
from datetime import datetime
from pathlib import Path

LAB = Path(__file__).resolve().parent
OUT = LAB / "STATE.md"
MIN_BET_DAYS = 30   # keep in step with run.MIN_BET_DAYS (not imported: run.py pulls in pandas + data)


def _jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()] if p.exists() else []


def build() -> str:
    trials = [r for r in _jsonl(LAB / "ledger.jsonl") if r.get("status") == "ok"]
    lockbox = _jsonl(LAB / "lockbox.jsonl")
    reg = _jsonl(LAB / "registry" / "strategies.jsonl")
    topics = json.loads((LAB / "registry" / "topics.json").read_text()) if (LAB / "registry" / "topics.json").exists() else []
    boxed = {r["sha"] for r in lockbox}

    L = [f"# Lab state ({datetime.now().strftime('%Y-%m-%d %H:%M')}, generated by lab/status.py; do not edit)", ""]
    L += ["## Trials by dataset", "",
          "| dataset | distinct strategies | promotion bar | best dev p (strategy) |", "|---|---|---|---|"]
    by_ds = defaultdict(list)
    for r in trials:
        by_ds[r["dataset"]].append(r)
    for ds, rows in sorted(by_ds.items()):
        n = len({r["sha"] for r in rows})
        best = min(rows, key=lambda r: r["p"])
        L.append(f"| {ds} | {n} | p < {0.05 / n:.5f} | {best['p']:.4f} ({best['strategy']}) |")

    L += ["", "## Dev candidates meeting their bar, not yet on the lockbox", ""]
    # Ledger rows before 2026-10-13 have no bet_days; a strategy has at most one betting day per
    # bet, so fewer than MIN_BET_DAYS bets rules it out, and more leaves the day count unknown.
    lookahead = {r["sha"]: ("pass" if r["pass"] else "FAIL") for r in _jsonl(LAB / "leakcheck.jsonl")}
    cands, thin = [], []
    for ds, rows in by_ds.items():
        n = len({r["sha"] for r in rows})
        for r in rows:
            if r["p"] >= 0.05 / n or r["sha"] in boxed:
                continue
            days = r.get("bet_days", r["bets"] if r["bets"] < MIN_BET_DAYS else None)
            (thin if days is not None and days < MIN_BET_DAYS else cands).append((ds, r))
    seen = set()
    for ds, r in sorted(cands, key=lambda x: x[1]["p"]):
        if r["sha"] in seen:
            continue
        seen.add(r["sha"])
        L.append(f"- {r['strategy']} ({ds}, sha {r['sha']}): {r['bets']} bets, ROI {r['roi']:+.1%}, p {r['p']:.4f}, "
                 f"folds positive {r['folds_positive']}/{len(r.get('per_fold', {}))}, "
                 f"lookahead {r.get('lookahead') or lookahead.get(r['sha'], 'not run: python lab/run.py leakcheck')}"
                 f"{'' if 'bet_days' in r else ', betting days not recorded'}. "
                 "Lockbox = human decision, after a critic review (lab/loop.sh critic).")
    if not seen:
        L.append("- none")
    for ds, r in thin:
        L.append(f"- (not a candidate) {r['strategy']} ({ds}): p {r['p']:.4f} on {r['bets']} bets -- under "
                 f"{MIN_BET_DAYS} betting days, the day-bootstrap p is not meaningful")

    L += ["", "## Lockbox (each strategy scored once, by a human)", ""]
    for r in lockbox:
        L.append(f"- {r['ts'][:10]} {r['strategy']} ({r['dataset']}): {r['bets']} bets, {r['units']:+.1f}u, "
                 f"ROI {r['roi']:+.2%}, p {r['p']:.4f}, found after {r['dev_trials']} dev trials")
    if not lockbox:
        L.append("- none")

    cited = set()
    for r in trials:
        cited |= set(re.findall(r"S\d{3}", str(r.get("source", ""))))
    testable = [e for e in reg if e.get("testable_with")]
    untried = [e for e in testable if e.get("id") not in cited]
    L += ["", "## Registry", "",
          f"{len(reg)} entries, {len(testable)} testable now, {len(untried)} testable with no trial citing them:"]
    for e in untried[:12]:
        L.append(f"- {e.get('id')} [{e.get('evidence')}] {e.get('title')} -> {', '.join(e['testable_with'])}")
    pending = [t for t in topics if t.get("status") == "pending"]
    L += ["", f"Research topics pending: {len(pending)}" + (f"; next {pending[0]['id']}: {pending[0]['topic'][:120]}"
                                                            if pending else "")]

    reps = sorted((LAB / "reports").glob("2*.md"))[-3:]
    L += ["", "## Latest reports", ""] + [f"- {p.name}" for p in reps]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = build()
    OUT.write_text(text)
    print(text)
